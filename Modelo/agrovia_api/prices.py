"""SIAP municipal price/yield lookup for POST /api/v1/precios.

The dataset is generated by ``Modelo/scripts/build_price_dataset.py`` from the raw SIAP
"cierre agrícola municipal" CSVs. This module only reads it: it does not correct, smooth or
impute any value. A missing field stays ``None`` all the way to the JSON response.
"""

from __future__ import annotations

import json
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

from .config import PRICES_PATH
from .schemas import PrecioRegistro, PreciosSIAP

CROP_ALIASES = {
    "frijol_pinto": "SIAP does not separate bean varieties; 'Frijol' represents frijol_pinto.",
}


def _normalize(text: str) -> str:
    decomposed = unicodedata.normalize("NFKD", text)
    without_accents = "".join(c for c in decomposed if not unicodedata.combining(c))
    return " ".join(without_accents.lower().strip().split())


@dataclass(frozen=True)
class SiapPriceDataset:
    fuente: str
    version: str
    records: tuple[dict[str, Any], ...]

    def lookup(self, cultivo_id: str, municipio: str) -> list[dict[str, Any]]:
        crop = _normalize(cultivo_id)
        municipality = _normalize(municipio)
        return [
            record for record in self.records
            if record["cultivo_id"] == crop and _normalize(record["municipio"]) == municipality
        ]

    def municipalities(self) -> set[str]:
        return {record["municipio"] for record in self.records}


@lru_cache(maxsize=1)
def load_price_dataset(path: Path = PRICES_PATH) -> SiapPriceDataset:
    with Path(path).open(encoding="utf-8") as handle:
        payload = json.load(handle)
    records = tuple(payload.get("registros", []))
    return SiapPriceDataset(
        fuente=str(payload.get("fuente", "SIAP Cierre agrícola municipal")),
        version=str(payload.get("version", "unknown")),
        records=records,
    )


def lookup_prices(
    dataset: SiapPriceDataset,
    cultivo_id: str,
    municipio: str,
    anio: int | None = None,
) -> PreciosSIAP:
    """Return the real SIAP rows for one crop/municipality, optionally narrowed to a year.

    An empty result is a valid answer (no rows for this crop/municipality/year); the caller gets
    a warning instead of a neighbourhood average or a fabricated price.
    """
    available = dataset.lookup(cultivo_id, municipio)
    warnings: list[str] = []
    alias = CROP_ALIASES.get(_normalize(cultivo_id))
    if alias:
        warnings.append(alias)

    if not available:
        warnings.append(
            f"No SIAP record for '{cultivo_id}' in '{municipio}'. "
            "No other municipality or crop was substituted."
        )
        return PreciosSIAP(
            fuente=dataset.fuente,
            version=dataset.version,
            cultivo_id=_normalize(cultivo_id),
            municipio=municipio,
            anio_ultimo=None,
            registros=[],
            advertencias=warnings,
        )

    years = sorted({int(record["anio"]) for record in available})
    anio_ultimo = years[-1]
    selected = [record for record in available if anio is None or int(record["anio"]) == anio]
    if anio is not None and not selected:
        warnings.append(
            f"SIAP has records for '{cultivo_id}' in '{municipio}' but none for {anio}; "
            f"available years: {', '.join(str(year) for year in years)}."
        )

    selected.sort(key=lambda r: (int(r["anio"]), r.get("ciclo") or "", r.get("modalidad") or ""))
    return PreciosSIAP(
        fuente=dataset.fuente,
        version=dataset.version,
        cultivo_id=_normalize(cultivo_id),
        municipio=available[0]["municipio"],
        anio_ultimo=anio_ultimo,
        registros=[PrecioRegistro(**record) for record in selected],
        advertencias=warnings,
    )
